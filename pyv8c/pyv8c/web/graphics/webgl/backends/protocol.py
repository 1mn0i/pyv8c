"""Operations implemented by each WebGL drawing backend."""
from typing import Protocol


class WebGLBackend(Protocol):
    def state(self, receiver, name, *values): ...
    def compile_shader(self, receiver, shader): ...
    def delete(self, receiver, value): ...
    def surface_pixels(self, receiver): ...
    def upload(self, receiver, target, data, usage, *arguments): ...
    def link_program(self, receiver, program, *arguments): ...
    def attrib_location(self, receiver, program, name, *arguments): ...
    def get_uniform_location(self, receiver, program, name, *arguments): ...
    def uniform1f(self, receiver, location, value, *arguments): ...
    def enable_vertex(self, receiver, index, *arguments): ...
    def vertex_pointer(self, receiver, index, size, kind, normalized, stride, offset, *arguments): ...
    def draw_arrays(self, receiver, mode, first, count, *arguments): ...
    def read_pixels(self, receiver, x, y, width, height, format, kind, pixels, *arguments): ...
